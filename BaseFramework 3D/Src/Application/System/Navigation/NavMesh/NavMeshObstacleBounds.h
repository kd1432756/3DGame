#pragma once

//============================================================
// NavMesh Obstacle Bounds
//============================================================
//
// NavMesh上で歩行不可となるObstacleのXZ Bounds。
//
// NavMeshGridでは、このBoundsを使って
// Cell内のWalkable PolygonをClipする。
//
// Y方向はNavMesh GridのPolygon Clipには使用しない。
//
//============================================================

struct NavMeshObstacleBounds
{
	//============================================================
	// X Bounds
	//============================================================

	float minX = 0.0f;
	float maxX = 0.0f;

	//============================================================
	// Z Bounds
	//============================================================

	float minZ = 0.0f;
	float maxZ = 0.0f;
};
